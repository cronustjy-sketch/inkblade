// Extracts story / chapter / boss data from the web game (public/index.html, read only) into data/*.gd files.
// Usage: node tools/extract_web_data.js
// English text comes from the web game's own I18N phrase table, applied the way its tr() does.
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', '..', 'public', 'index.html'), 'utf8');
const lines = src.split('\n');

function find(re, from = 0) { for (let i = from; i < lines.length; i++) if (re.test(lines[i])) return i; throw new Error('not found ' + re); }
function slice(a, b) { return lines.slice(a, b + 1).join('\n'); }

// --- I18N (en) ---
const i18nLine = lines[find(/^<script>window\.I18N=/)];
const w = {};
new Function('window', i18nLine.replace(/^<script>/, '').replace(/<\/script>\s*$/, ''))(w);
const EN = w.I18N.en;
const keys = Object.keys(EN).sort((a, b) => b.length - a.length);
const PUNC = { '。': '. ', '，': ', ', '：': ': ', '！': '! ', '？': '? ', '（': ' (', '）': ') ', '、': ', ', '「': '"', '」': '"', '；': '; ', '＝': '=', '　': ' ' };
function esc(k) { return k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
const TRK = new RegExp(keys.map(esc).join('|'), 'g');
function tr(t) {
  if (typeof t !== 'string' || !/[　-鿿＀-￯]/.test(t)) return t;
  return t.replace(/第\s*(\d+)\s*回合/g, (m, n) => 'Round ' + n).replace(TRK, m => EN[m]).replace(/[。，：！？（）、「」；＝　]/g, m => PUNC[m]).replace(/ {2,}/g, ' ').trim();
}

// --- chapters ---
const c0 = find(/^const CHAPTERS=\[/), c1 = find(/^DARKCH\.forEach/);
const chapters = new Function(slice(c0, c1) + '\nreturn CHAPTERS;')();

// --- story ---
const s0 = find(/^const STORY=\[/), s1 = find(/^function showStory/);
const story = new Function(slice(s0, s1 - 1) + '\nreturn STORY;')();

// --- chapter dialogue ---
const h0 = find(/^const CHF=\{/), h1 = find(/^function showChStory/);
const h2 = find(/^CHS\[28\]=/), h3 = find(/^const LEGX=/);
const dlg = new Function(slice(h0, h1 - 1) + '\n' + slice(h2, h3 - 1) + '\nreturn {CHF,CHS};')();

function gd(v) { return JSON.stringify(v, null, '\t'); }
const out = [];
out.push('# Generated by tools/extract_web_data.js from the web game. Do not edit by hand.');
out.push('extends RefCounted');
out.push('');
out.push('# Opening story pages: {i: icon, t: title, s: subtitle}; STORY_EN has the English at the same index.');
out.push('const STORY: Array = ' + gd(story));
out.push('const STORY_EN: Array = ' + gd(story.map(p => ({ t: tr(p.t), s: tr(p.s) }))));
out.push('');
out.push('# Chapters 1-60: n, a (first level), b (last level), t (Chinese title), e (English title), d (rule text), intro, theme.');
const chOut = chapters.map(c => ({ n: c.n, a: c.a, b: c.b, t: c.t, e: c.e, d: c.d, d_en: tr(c.d), intro: c.intro || '', intro_en: tr(c.intro || ''), theme: c.theme || '', ic: c.ic || '' }));
out.push('const CHAPTERS: Array = ' + gd(chOut));
out.push('');
out.push('# Chapter story scenes: chapter -> [{w: speaker, t: Chinese, en: English}]; speakers y=you m=墨老 f=foe s=shadow n=narration.');
const chs = {};
for (const k of Object.keys(dlg.CHS)) chs[k] = dlg.CHS[k].map(([wh, t, x]) => ({ w: wh, t: t, en: tr(t), x: x || '' }));
out.push('const CHS: Dictionary = ' + gd(chs));
out.push('const CHF: Dictionary = ' + gd(dlg.CHF));
out.push('const CHF_EN: Dictionary = ' + gd(Object.fromEntries(Object.entries(dlg.CHF).map(([k, v]) => [k, tr(v)]))));
fs.writeFileSync(path.join(__dirname, '..', 'data', 'story_data.gd'), out.join('\n') + '\n');
console.log('chapters', chOut.length, 'story', story.length, 'chs', Object.keys(chs).length, 'EN keys', keys.length);
console.log(JSON.stringify(story.map(p => ({ t: tr(p.t), s: tr(p.s) })), null, 1));
console.log(chOut[0].d_en, '|', chs[1][0].t, '|', chs[1][0].en, '|', chs[2][0].en);
