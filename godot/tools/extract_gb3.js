// Extracts the web game's 3D campaign boss table (GB3) and move names (GMVN) into data/gb3_data.gd. Read only on public/.
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', '..', 'public', 'index.html'), 'utf8');
const lines = src.split('\n');
function find(re) { for (let i = 0; i < lines.length; i++) if (re.test(lines[i])) return i; throw new Error('nf ' + re); }
const a = find(/^const GB3=\[/);
let b = a; while (!/^const GMVN=/.test(lines[b])) b++;
const code = lines.slice(a, b + 1).join('\n') + '\nreturn {GB3,GMVN};';
const r = new Function(code)();
const bosses = r.GB3.filter(x => x).map(x => ({
  name_cn: x.n, name_en: x.e, tip_cn: x.t || '', body: x.b,
  colors: x.c.map(n => '#' + n.toString(16).padStart(6, '0')),
  parts: x.p || [], moves: x.m, moves2: x.p2 || [], hp: x.hp, speed: x.sp
}));
const out = ['# GENERATED by tools/extract_gb3.js from the web game (GB3 + GMVN). Do not edit by hand.', 'extends RefCounted', ''];
out.push('const BOSSES: Array[Dictionary] = ' + JSON.stringify(bosses, null, '\t').replace(/"#([0-9a-f]{6})"/g, 'Color("$1")'));
out.push('');
const mv = {}; for (const k in r.GMVN) mv[k] = { cn: r.GMVN[k][0], tip: r.GMVN[k][1] };
out.push('const MOVE_NAMES: Dictionary = ' + JSON.stringify(mv, null, '\t'));
fs.writeFileSync(path.join(__dirname, '..', 'data', 'gb3_data.gd'), out.join('\n') + '\n');
console.log('bosses', bosses.length);
